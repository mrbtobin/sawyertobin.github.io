#!/usr/bin/env python3
"""Add books from one authored JS file without rebuilding or deleting other books."""
import json
import subprocess
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
if len(sys.argv) != 2:
    raise SystemExit('Usage: python3 shellfie/tools/add_authored_books.py shellfie/tools/authored/queue_name.js')
source = Path(sys.argv[1]).resolve()
if source.parent != (root / 'tools' / 'authored').resolve() or not source.is_file():
    raise SystemExit('Supply an existing file in shellfie/tools/authored/')
js = 'global.window={SHELLFIE_STORIES:[]};require(process.argv[1]);process.stdout.write(JSON.stringify(window.SHELLFIE_STORIES));'
books = json.loads(subprocess.check_output(['node','-e',js,str(source)], text=True))
if not books:
    raise SystemExit('No books found')
catalog_path = root / 'catalog.js'
s = catalog_path.read_text(encoding='utf-8')
catalog, _ = json.JSONDecoder().raw_decode(s[s.index('=') + 1:].strip())
outputs = []
ids = set()
for b in books:
    bid = b['id']; path = root / 'books' / (bid + '.json')
    if '/' in bid or '\\' in bid or bid in ids or path.exists():
        raise SystemExit(f'Unsafe, duplicate or existing book ID: {bid}')
    ids.add(bid)
    matches = [e for e in catalog[b['lang']][b['grade']] if e.get('t') == b['title']]
    if len(matches) != 1 or matches[0].get('id'):
        raise SystemExit(f'{bid}: expected exactly one unlinked catalog entry')
    for ch in b['chapters']:
        text = ' '.join(ch['pages'])
        if len(ch.get('quiz', [])) != 3:
            raise SystemExit(f'{bid}: every chapter needs three quiz questions')
        for q in ch['quiz']:
            if not q.get('ev') or q['ev'] not in text or not isinstance(q.get('a'), int) or not 0 <= q['a'] < len(q.get('o', [])):
                raise SystemExit(f'{bid}: invalid quiz evidence or answer')
    b['human'] = False
    entry = matches[0]
    entry.update({'a':b['author'],'g':b['genre'],'id':bid,'icon':b['icon'],'pc':[len(ch['pages']) for ch in b['chapters']]})
    outputs.append((path,b))
for path,b in outputs:
    path.write_text(json.dumps(b,ensure_ascii=False,separators=(',',':')),encoding='utf-8')
catalog_path.write_text('/* Shellfie catalog: generated by tools/build_library.py. Entries with an id are readable (books/<id>.json). */\nwindow.SHELLFIE_CATALOG = '+json.dumps(catalog,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
print('Added:', ', '.join(b['id'] for _,b in outputs))
